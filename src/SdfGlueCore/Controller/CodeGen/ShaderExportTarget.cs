using SdfGlueCore.Controller.CodeGen;
using SdfGlueCore.Model;
using SdfGlueCore.Model.DataNodes;
using SingleDocAppCore.Model.DataNodes;
using System.Text;

namespace SdfGlueCore.Controller
{
    // Target of the generated code: the editor preview or an export format.
    // Describes the template and the code generation policy; parts of the generator ask the target.
    public abstract class ShaderExportTarget
    {
        public static readonly ShaderExportTarget   Preview     = new PreviewTarget();
        public static readonly ShaderExportTarget   Shadertoy   = new ShadertoyTarget();
        public static readonly ShaderExportTarget   Unity       = new UnityTarget();

        public abstract string Name { get; }

        // Template file with ShaderCodeGenerator.GeneratedCodeTag; null - only the generated code
        public virtual string? TemplatePath             { get { return null; } }

        // Extension of the exported file (without a dot)
        public virtual string FileExtension             { get { return "glsl"; } }

        // All parameters are generated as constants (camera, objects, materials, renderer, backdrop)
        public virtual bool ForceFixed                  { get { return false; } }

        // Parameters driven by signals are exported with their static values
        // (otherwise they stay uniforms set by the editor, also in fixed objects)
        public virtual bool UseStaticSignalValues       { get { return false; } }

        // Code at the beginning of the generated code
        public virtual void AppendHeader(CodeGenContext ctx)
        {
        }

        // Body of sdfg_setupCamera() - by default the calls of the camera operators (appendOperatorsCalls)
        public virtual void AppendCameraSetup(CodeGenContext ctx, Action appendOperatorsCalls)
        {
            appendOperatorsCalls();
        }

        // Modification of the generated code (before it is inserted into the template)
        public virtual string PostProcessGeneratedCode(CodeGenContext ctx, string code)
        {
            return code;
        }

        // Last modification of the whole shader (template + generated code)
        public virtual string PostProcess(CodeGenContext ctx, string shader)
        {
            return shader;
        }
    }

    // Editor preview (Shaders/Template.frag, uniforms set by RenderPass every frame)
    public class PreviewTarget : ShaderExportTarget
    {
        public override string Name                     { get { return "Preview"; } }
        public override string? TemplatePath            { get { return "Shaders/Template.frag"; } }
        public override string FileExtension            { get { return "frag"; } }
    }

    // Shadertoy (shadertoy.com, GLSL ES 3.00): only the generated code, the "Image" tab defines mainImage().
    // Uniforms are not possible (no initializers, no way to set them) - all parameters become constants.
    public class ShadertoyTarget : ShaderExportTarget
    {
        public override string Name                     { get { return "Shadertoy"; } }
        public override bool ForceFixed                 { get { return true; } }
        public override bool UseStaticSignalValues      { get { return true; } }

        public override void AppendHeader(CodeGenContext ctx)
        {
            StringBuilder sb = ctx.Code;

            sb.AppendLine("//-------------------------------------------------------------------------------");
            sb.AppendLine(String.Format("// Generated by SdfGlue {0} (https://github.com/luk77/sdfglue)", DataModel.GetAppDisplayVersion()));
            sb.AppendLine(String.Format("// Pass: {0}", ctx.Pass.Name.Val));

            if (ctx.Model.HasSignalBindings())
                sb.AppendLine("// NOTE: parameters driven by signals are exported with their static values");

            int passesCount = 0;
            foreach (TreeNode node in ctx.Model.RenderingSysData.Children)
            {
                if (node is RenderPassData pass && pass.Enabled.Val)
                    passesCount++;
            }
            if (passesCount > 1)
                sb.AppendLine("// NOTE: only this pass is exported - other passes of the project (e.g. accumulation of frames) are not included");

            sb.AppendLine("//-------------------------------------------------------------------------------");
            sb.AppendLine();
        }
    }

    // Unity shader (experimental): Shaders/UnityTemplate.shader, the generated code translated to HLSL (GlslToHlslTranslator).
    // Uniforms without material properties are not set by Unity - all parameters become constants.
    // World space mode (material toggle SDFG_WORLD_SPACE): sdfg_setupCamera() uses the ray of the Unity camera.
    public class UnityTarget : ShaderExportTarget
    {
        public override string Name                     { get { return "Unity"; } }
        public override string? TemplatePath            { get { return "Shaders/UnityTemplate.shader"; } }
        public override string FileExtension            { get { return "shader"; } }
        public override bool ForceFixed                 { get { return true; } }
        public override bool UseStaticSignalValues      { get { return true; } }

        public override void AppendHeader(CodeGenContext ctx)
        {
            StringBuilder sb = ctx.Code;

            sb.AppendLine("//-------------------------------------------------------------------------------");
            sb.AppendLine(String.Format("// Generated by SdfGlue {0} (https://github.com/luk77/sdfglue)", DataModel.GetAppDisplayVersion()));
            sb.AppendLine(String.Format("// Pass: {0}", ctx.Pass.Name.Val));
            if (ctx.Model.HasSignalBindings())
                sb.AppendLine("// NOTE: parameters driven by signals are exported with their static values");
            sb.AppendLine("// NOTE: the world space mode works with renderers that use sdfg_setupCamera()");
            sb.AppendLine("//-------------------------------------------------------------------------------");
            sb.AppendLine();
        }

        public override void AppendCameraSetup(CodeGenContext ctx, Action appendOperatorsCalls)
        {
            ctx.Code.AppendLine("#ifdef SDFG_WORLD_SPACE");
            ctx.Code.AppendLine("    ro = sdfg_unityRo;");
            ctx.Code.AppendLine("    rd = sdfg_unityRd;");
            ctx.Code.AppendLine("#else");
            appendOperatorsCalls();
            ctx.Code.AppendLine("#endif");
        }

        public override string PostProcessGeneratedCode(CodeGenContext ctx, string code)
        {
            return new GlslToHlslTranslator().Translate(code);
        }

        public override string PostProcess(CodeGenContext ctx, string shader)
        {
            return shader.Replace("__shader_name__", GetShaderName(ctx.ExportName));
        }

        // Name in the Unity shader menu ("SdfGlue/<name>")
        private static string GetShaderName(string? exportName)
        {
            if (String.IsNullOrWhiteSpace(exportName))
                return "Exported";

            StringBuilder sb = new StringBuilder();
            foreach (char c in exportName)
                sb.Append((Char.IsLetterOrDigit(c) || c == '_' || c == '-' || c == ' ') ? c : '_');
            return sb.ToString();
        }
    }
}
